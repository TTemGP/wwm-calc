from PIL import Image
_ICON_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "src", "assets", "path-icons")
_icons = {}
def icon(b, size):
    key = b["en"].split("–")[1].lower()
    if key not in _icons:
        im = Image.open(os.path.join(_ICON_DIR, key + ".png")).convert("RGBA").resize((96, 96), Image.LANCZOS)
        buf = io.BytesIO(); im.save(buf, "WEBP", quality=88)
        _icons[key] = "data:image/webp;base64," + base64.b64encode(buf.getvalue()).decode()
