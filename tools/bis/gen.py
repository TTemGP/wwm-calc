def expand(row):
    cells = []
    for tok in row.split(","):
        tok = tok.strip()
        m = re.match(r"^(.*?)x(\d+)$", tok)
        if m:
            cells += [m.group(1)] * int(m.group(2))
        else:
            cells.append(tok)
    if len(cells) != 8:
        raise ValueError(f"row has {len(cells)} cells: {row}")
    return cells

GOD = {"전비증", "보피증", "전무증", "우무증", "북피증", "검무증", "맥무증", "권무증", "쌍무증", "승무증"}

def grid(rows, slot_names):
    out = ['<div class="tbl"><table class="grid"><thead><tr><th>줄</th>']
    out += [f"<th>{s}</th>" for s in slot_names]
    out.append("</tr></thead><tbody>")
    for i, r in enumerate(rows, 1):
        out.append(f"<tr><td>{i}</td>")
        for c in expand(r):
            free = c.endswith("*")
            name = c.rstrip("*")
            cls = []
            if free: cls.append("free")
            if name in GOD: cls.append("god")
            out.append(f'<td class="{" ".join(cls)}">{html.escape(name)}</td>')
        out.append("</tr>")
    out.append("</tbody></table></div>")
    return "".join(out)

def tally(rows):
    from collections import Counter
    c = Counter()
    for r in rows:
        for x in expand(r):
            n = x.rstrip("*")
            c["신력" if n in GOD else n] += 1
    return c

